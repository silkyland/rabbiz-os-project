import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../A21s/Services/ChargingEvents.js', import.meta.url), 'utf8')
  .replace(/^\.pragma library\s*$/m, '');
const box = { module: { exports: {} } };
vm.runInNewContext(source, box);
const { create, sample, connection } = box.module.exports;
let s = sample(create(), true, 0);
assert.equal(s.event, '', 'already plugged in at boot does not notify');
s = sample(s, false, 1000);
s = sample(s, true, 1500);
assert.equal(s.event, '', 'a brief telemetry fluctuation does not notify');
s = sample(s, false, 2000);
s = sample(s, false, 4000);
assert.equal(s.event, 'stopped');
s = sample(s, true, 6000);
assert.equal(s.event, '', 'wait for stable charging');
s = sample(s, true, 8000);
assert.equal(s.event, 'started');
s = sample(s, true, 10000);
assert.equal(s.event, '', 'one notification per charging transition');
s = sample(s, true, 12000);
assert.equal(s.event, '', 'reaching full is not a new cable connection');
s = sample(s, null, 14000);
assert.equal(s.connected, true, 'missing telemetry preserves the known state');
let empty = sample(create(), null, 0);
assert.equal(empty.primed, false);
assert.equal(sample(empty, false, 1000).event, '');
console.log('charging events: ok');
assert.equal(connection('Discharging', 'configured'), true, 'USB power is present even under net battery drain');
assert.equal(connection('Discharging', 'not attached'), false);
assert.equal(connection('Charging', 'not attached'), true, 'wall charging does not require a USB host');
assert.equal(connection('Unknown', ''), null);
